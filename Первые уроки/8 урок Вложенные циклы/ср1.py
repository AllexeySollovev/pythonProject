bal=int(input("Введите оценку ученика: "))
if bal==5:
    print("Молодец,Твоя отметка-отлично")
elif bal==4:
    print("Интересный результат. Ты хорошо поработал!")
elif bal==3:
    print("Удовлетворительно,Стоит поработать над ошибками!")
elif bal==2:
    print("Работа плоха. Приходи на перемене, чтобы все исправить!")
else:
    print("Неверная оценка!")